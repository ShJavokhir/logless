"""Synthetic reconstruction eval (the Clio check): does the pipeline recover a mix it was not told?

1. `logless synth --n 5000 --out DIR` has GLM write conversations from the known mix in
   synthetic_mix.json. It writes DIR/conversations.jsonl and DIR/source.json for `logless import`,
   and keeps the true labels aside in DIR/truth.jsonl.
2. Import DIR into a new data directory and run `logless rebuild` there, exactly as for real data.
3. `logless reconstruct DIR/truth.jsonl` (same LOGLESS_DATA_DIR) scores the published build against
   the truth, overall, per language and per facet model lane (the model that wrote each summary).

Scores: ARI between true topic and leaf; TVD between the true topic mix and the mix the leaves imply
(each leaf counts as its majority true topic; cl_other counts as "unassigned"); and precision/recall
of Jev's `correction` signal against the planted corrections. Groups under MIN_GROUP conversations
get no scores. Nothing here is published; the report is a private artifact.
"""
from __future__ import annotations

import json
import logging
import random
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from .. import db
from ..config import GLM_FLASH, settings
from ..ids import conversation_id

log = logging.getLogger("logless.eval.reconstruct")

MIX_PATH = Path(__file__).resolve().parent / "synthetic_mix.json"
MIN_GROUP = 30
MAX_FAILED_SHARE = 0.05

SOURCE_METADATA = {
    "name": "Synthetic reconstruction mix", "workspace_name": "Reconstruction eval",
    "workspace_description": "Synthetic conversations from a known topic and language mix, written by GLM.",
    "source_url": "https://example.org/logless/synthetic-mix", "revision": "mix-v1",
    "license": "Team-owned synthetic data", "attribution": "Generated by the logless reconstruction eval",
    "people_note": "People are synthetic user IDs, each with a fixed number of conversations.",
    "intended_uses": ["Answer everyday questions", "Help with writing", "Help with code"],
}

SYNTH_SYS = """You write one realistic chat between a person and an AI assistant, for testing an analytics tool.
Topic: {topic}.
Language: write every message, from both sides, in {language}.
{friction}
Invent a concrete, specific situation so that this chat differs from other chats on the same topic.
Use 2 to 6 messages, starting with the person. Do not use real names, email addresses, phone numbers or URLs."""
WITH_CORRECTION = "The assistant's first answer contains a clear mistake. The person points out the mistake and the assistant corrects it."
WITHOUT_CORRECTION = "The conversation goes smoothly. The person never says that the assistant made a mistake."


class Message(BaseModel):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=4000)


class SynthChat(BaseModel):
    messages: list[Message] = Field(min_length=2, max_length=8)


def load_mix() -> dict:
    return json.loads(MIX_PATH.read_text())


def plan(n: int, seed: int, mix: dict) -> list[dict]:
    """The truth rows: topic, language, planted correction and synthetic person for each conversation."""
    rng = random.Random(seed)
    topics = [t["id"] for t in mix["topics"]]
    langs = list(mix["languages"])
    rows = []
    for i in range(n):
        rows.append({"id": f"synth-{i:06d}", "topic": rng.choices(topics, [t["weight"] for t in mix["topics"]])[0],
                     "language": rng.choices(langs, list(mix["languages"].values()))[0],
                     "correction": rng.random() < mix["correction_rate"]})
    people = max(1, n // mix["conversations_per_person"])
    for r in rows:
        r["user_id"] = f"person-{rng.randrange(people):05d}"
    return rows


def _write_one(t: dict, desc: dict[str, str]) -> dict | None:
    from ..providers import glm
    system = SYNTH_SYS.format(topic=desc[t["topic"]], language=t["language"],
                              friction=WITH_CORRECTION if t["correction"] else WITHOUT_CORRECTION)
    try:
        chat, _ = glm.chat_json(system, f"Chat number {t['id']}.", SynthChat, model=GLM_FLASH, temperature=1.0, max_tokens=2000)
    except Exception as e:
        log.warning("%s not written (%s)", t["id"], type(e).__name__)
        return None
    if chat.messages[0].role != "user":
        return None
    return {"id": t["id"], "user_id": t["user_id"], "language": t["language"], "model": "synthetic",
            "messages": [m.model_dump() for m in chat.messages]}


def synth(n: int, out: Path, seed: int = 7, workers: int = 16) -> dict:
    """Write DIR/conversations.jsonl, DIR/source.json and DIR/truth.jsonl. Fails if too many chats fail."""
    mix = load_mix()
    truth = plan(n, seed, mix)
    desc = {t["id"]: t["description"] for t in mix["topics"]}
    with ThreadPoolExecutor(max_workers=workers) as ex:
        chats = list(ex.map(lambda t: _write_one(t, desc), truth))
    kept = [(t, c) for t, c in zip(truth, chats) if c is not None]
    failed = n - len(kept)
    if failed > MAX_FAILED_SHARE * n:
        raise RuntimeError(f"{failed} of {n} synthetic chats failed; not writing a biased corpus")
    out.mkdir(parents=True, exist_ok=True)
    (out / "conversations.jsonl").write_text("".join(json.dumps(c, ensure_ascii=False) + "\n" for _, c in kept))
    (out / "truth.jsonl").write_text("".join(json.dumps(t) + "\n" for t, _ in kept))
    (out / "source.json").write_text(json.dumps(SOURCE_METADATA, indent=1))
    return {"written": len(kept), "failed": failed, "out": str(out)}


# ---------------------------------------------------------------- scoring

def _tvd(true: list[str], pred: list[str]) -> float:
    n = len(true)
    p, q = Counter(true), Counter(pred)
    return round(0.5 * sum(abs(p[k] - q[k]) for k in set(p) | set(q)) / n, 4)


def _scores(rows: list[dict], leaf_topic: dict[str, str]) -> dict:
    from sklearn.metrics import adjusted_rand_score
    n = len(rows)
    out: dict = {"conversations": n}
    if n < MIN_GROUP:
        return out
    true = [r["topic"] for r in rows]
    out["ari"] = round(float(adjusted_rand_score(true, [r["leaf_id"] for r in rows])), 4)
    out["tvd"] = _tvd(true, [leaf_topic.get(r["leaf_id"], "unassigned") for r in rows])
    decided = [r for r in rows if r["correction_choice"] != "unclear"]
    tp = sum(1 for r in decided if r["correction"] and r["correction_choice"] == "observed")
    obs = sum(1 for r in decided if r["correction_choice"] == "observed")
    real = sum(1 for r in decided if r["correction"])
    out["correction"] = {"true_rate": round(sum(r["correction"] for r in rows) / n, 4),
                         "observed_rate": round(obs / n, 4),
                         "precision": round(tp / obs, 4) if obs else None,
                         "recall": round(tp / real, 4) if real else None,
                         "unclear": n - len(decided)}
    return out


def score(truth_path: Path, build_id: str) -> dict:
    from ..pipeline import stats, util
    truth = {}
    for line in truth_path.read_text().splitlines():
        if line.strip():
            t = json.loads(line)
            truth[conversation_id("jsonl:" + t["id"])] = t
    st = util.Build(build_id=build_id, limit=None, conv_ids=[], started_at="").load("structure_final")
    rows = [r for r in stats.assignment_rows(build_id, stats.clusters_for(st)) if r["conv_id"] in truth]
    if not rows:
        raise RuntimeError("no scored conversations: is this the data directory the truth file was imported into?")
    lanes = {r["conv_id"]: r["model"] or "unknown" for r in db.private().execute("SELECT conv_id, model FROM facets")}
    for r in rows:
        t = truth[r["conv_id"]]
        r.update(topic=t["topic"], true_language=t["language"], correction=t["correction"],
                 correction_choice=r["correction"], lane=lanes.get(r["conv_id"], "unknown"))
    by_leaf: dict[str, Counter] = defaultdict(Counter)
    for r in rows:
        by_leaf[r["leaf_id"]][r["topic"]] += 1
    leaf_topic = {lid: c.most_common(1)[0][0] for lid, c in by_leaf.items() if lid != "cl_other"}
    titles = {l["id"]: l["title"] for l in st["leaves"]}
    report = {
        "build_id": build_id,
        "overall": _scores(rows, leaf_topic),
        "by_language": {k: _scores([r for r in rows if r["true_language"] == k], leaf_topic)
                        for k in sorted({r["true_language"] for r in rows})},
        "by_lane": {k: _scores([r for r in rows if r["lane"] == k], leaf_topic) for k in sorted({r["lane"] for r in rows})},
        "leaves": [{"id": lid, "title": titles.get(lid, ""), "conversations": sum(c.values()),
                    "topic": leaf_topic.get(lid, "unassigned"), "purity": round(c.most_common(1)[0][1] / sum(c.values()), 4)}
                   for lid, c in sorted(by_leaf.items(), key=lambda kv: -sum(kv[1].values()))],
        "missing_topics": sorted({r["topic"] for r in rows} - set(leaf_topic.values())),
        "unmatched_truth": len(truth) - len(rows),
    }
    d = settings().artifacts_dir / "eval"
    d.mkdir(parents=True, exist_ok=True)
    (d / "reconstruct.json").write_text(json.dumps(report, ensure_ascii=False, indent=1))
    return report


def current_build() -> str:
    from ..intake import build_of_snapshot, current_snapshot
    snap = current_snapshot()
    build_id = build_of_snapshot(snap["snapshot_id"]) if snap else None
    if build_id is None:
        raise RuntimeError("no published build in this data directory; run `logless rebuild` first")
    return build_id
